public class KeyPerkTeleportDrops extends KeyPerk {

    public static final MapCodec<KeyPerkTeleportDrops> CODEC = RecordCodecBuilder.mapCodec(inst -> perkModifierFields(inst).apply(inst, KeyPerkTeleportDrops::new));
    public static final PerkType<KeyPerkTeleportDrops> TYPE =
            PerkType.of(KeyPerkTeleportDrops.CODEC, PerkDataTypesAS.DEFAULT_DATA, KeyPerkTeleportDrops::new);

    private KeyPerkTeleportDrops(ResourceLocation key, float x, float y) {
        this(key, defaultNameKey(key), x, y, PerkCategory.MAJOR, Collections.emptySet(), Collections.emptySet(), Collections.emptySet());
    }

    protected KeyPerkTeleportDrops(ResourceLocation key, String nameKey, float x, float y, PerkCategory category, Collection<PerkRequirement> requirements, Collection<PerkAttributeConverter> converters, Collection<PerkAttributeModifier> modifiers) {
        super(key, nameKey, x, y, category, requirements, converters, modifiers);
    }

    @Override
    public PerkType<?> getType() {
        return TYPE;
    }
}
